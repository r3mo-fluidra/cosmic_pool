# message dict and on every score sent to Langfuse — it is tracking data for
# us, so it belongs in the console, not on the user's screen.


def _submit_and_store(
    trace_id: str,
    value: int,
    turn_index: int | None,
    lang: str,
) -> None:
    """
    One thumb click: persist the score, remember it locally, repaint.

    The negative case stores the 0 immediately rather than waiting for the
    detail form to be completed — if the reader walks away we still keep the
    signal, and `score_id` is deterministic so finishing the form upserts the
    same row instead of adding a second one.

    `note` is the comment stored on the score, not something the reader sees, so
    it stays in one language: it is queried out of the Langfuse console and a
    comment that changed language per turn would be harder to filter, not
    easier. Only the toast follows the reader.
    """
    note = "Respuesta útil" if value == 1 else "Respuesta no útil (pendiente de detalle)"

    # The verdict is stored *before* the score is sent, and regardless of whether
    # sending works. Gating it on the send made the control's appearance depend on
    # telemetry: with no Langfuse client `submit_feedback` returns False, so the
    # thumb stayed unselected and the tap read as a dead button. Whether the score
    # reached Langfuse is a telemetry outcome; whether the reader's tap registered
    # is not, and the two do not belong on the same conditional.
    st.session_state.feedback[trace_id] = {
        "value": value,
        "reason": None,
        "awaiting_detail": value == 0,
    }

    # `submit_feedback` raises its own toast when it cannot record, so the thanks
    # is only shown when there is something to be thankful for — two contradicting
    # toasts would be worse than none.
    if submit_feedback(trace_id, value, note, turn_index=turn_index):
        st.toast(form_label(lang, "thanks_verdict"))
    st.rerun()


def _clear_verdict(trace_id: str) -> None:
    """
    Second tap on the already-chosen thumb: undo the selection.

    Only the local verdict is dropped, which is what returns the button to
    "secondary" and its unselected colour. It also takes `awaiting_detail` with
    it, so an open thumbs-down form closes rather than being left orphaned.

    The score already sent to Langfuse under the deterministic `score_id` is
    deliberately left in place: removing it is a telemetry decision, not a UI
    one. A later click on either thumb upserts that same row as before.
    """
    st.session_state.feedback.pop(trace_id, None)
    st.rerun()


def render_sources(msg: ChatMessage, trace_id: str, lang: str) -> None:
    """
    The panel the "View sources" menu item opens, under the answer it belongs to.

    It reports what the turn actually carries. Nothing populates
    `AgentResult.sources` today, so in practice this says the answer was not
    linked to a document — which is the honest statement, and the same reason
    the status line stopped naming a manual section (§8.2). The moment the
    backend starts returning sources, they appear here with no change.
    """
    if not st.session_state.sources_open.get(trace_id):
        return

    with st.container(key=f"pa-sources-{trace_id}"):
        st.markdown(
            f'<div class="pa-src-title">'
            f'{html.escape(action_label(lang, "sources_title"))}</div>',
            unsafe_allow_html=True,
        )
        sources = sources_of(msg)
        if sources:
            st.markdown(
                "".join(
                    '<div class="pa-src-item"><span>·</span>'
                    f"<span>{html.escape(src)}</span></div>"
                    for src in sources
                ),
                unsafe_allow_html=True,
            )
        else:
            st.markdown(
                f'<div class="pa-src-empty">'
                f'{html.escape(action_label(lang, "sources_empty"))}</div>',
                unsafe_allow_html=True,
            )
        if st.button(action_label(lang, "hide"), key=f"hidesrc_{trace_id}"):
            st.session_state.sources_open[trace_id] = False
            st.rerun()


def render_feedback_detail(trace_id: str, turn_index: int | None, lang: str) -> None:
    """
    The follow-up a thumbs-down opens: a category and an optional note.

    Two kinds of string meet in here and are kept apart deliberately:

      * what the reader sees — the prompt, the field labels, the placeholder,
        the two controls, the category names — follows the language the turn was
        written in, through `copy.py` like the rest of the chrome. This form used
        to be the one part of the UI that ignored that, hardcoding Spanish inside
        otherwise-English chrome with English category names beside it;
      * what Langfuse stores — the values in `REASON_ORDER` and the fallback
        comment — is frozen and never localised. A stored value that changed
        with the reader's language would split one category's history in two.
    """
    state = st.session_state.feedback.get(trace_id)
    if not (state and state.get("awaiting_detail")):
        return

    with st.container(key=f"pa-detail-{trace_id}"):
        st.caption(form_label(lang, "detail_prompt"))
        # {display label: stored value}, in the taxonomy's own order.
        choices = reason_choices(lang)
        label = st.selectbox(
            form_label(lang, "reason_label"),
            options=list(choices),
            key=f"reason_{trace_id}",
        )
        detail = st.text_area(
            form_label(lang, "detail_label"),
            key=f"detail_{trace_id}",
            placeholder=form_label(lang, "detail_placeholder"),
            height=80,
        )
        # A horizontal container, not `st.columns([1, 1, 6])`.
        #
        # The columns split the scroll area's 344px into ~40px each, which is
        # narrower than either label: the buttons rendered one letter per line,
        # in every language. Nobody had reported it because the form above them
        # was unreadable, so no tester ever got this far.
        #
        # This is how every other button row in the app is laid out —
        # `render_answer_actions`, `pa-chips`, `pa-reset` — and the pills hug
        # their own text, so it holds for a label of any length.
        with st.container(
            key=f"pa-detail-actions-{trace_id}",
            horizontal=True,
            vertical_alignment="center",
        ):
            if st.button(
                form_label(lang, "send"), key=f"send_{trace_id}", type="primary"
            ):
                reason = choices[label]
                comment = detail.strip() or f"({reason}) sin detalle"
                # Same score_id as the initial negative click -> upsert, not a duplicate.
                if submit_feedback(trace_id, 0, comment, reason=reason, turn_index=turn_index):
                    st.session_state.feedback[trace_id] = {
                        "value": 0,
                        "reason": reason,
                        "awaiting_detail": False,
                    }
                    st.toast(form_label(lang, "thanks_detail"))
                    st.rerun()

            if st.button(form_label(lang, "skip"), key=f"skip_{trace_id}"):
                # The value=0 score is already persisted; nothing to send.
                st.session_state.feedback[trace_id] = {
                    "value": 0,
                    "reason": None,
                    "awaiting_detail": False,
                }
                st.rerun()


def render_answer_actions(msg: ChatMessage) -> None:
    """
    The row under an assistant answer: two thumbs, then a "…" menu.

    Rendered from the history loop (NOT from inside the `chat_input` block), so
    it survives the rerun its own buttons trigger — the same constraint
    FRONTEND.md §11.9 records — and *outside* `st.chat_message`, so it sits
    under the card rather than inside it.

    The chosen thumb keeps the accent, which is how the row remembers a verdict
    without spending a sentence on it.
    """
    if not SHOW_PER_ANSWER_FEEDBACK:
        return
    trace_id = msg.get("trace_id")
    if not trace_id:
        return

    turn_index = msg.get("turn_index")
    lang = msg.get("language") or detect_language(msg.get("content", ""))
    state = st.session_state.feedback.get(trace_id)
    verdict = state.get("value") if state else None

    with st.container(
        key=f"pa-actions-{trace_id}",
        horizontal=True,
        vertical_alignment="center",
    ):
        if st.button(
            ":material/thumb_up:",
            key=f"good_{trace_id}",
            help=action_label(lang, "helpful"),
            type="primary" if verdict == 1 else "secondary",
        ):
            if verdict == 1:
                _clear_verdict(trace_id)
            else:
                _submit_and_store(trace_id, 1, turn_index, lang)
        if st.button(
            ":material/thumb_down:",
            key=f"bad_{trace_id}",
            help=action_label(lang, "not_helpful"),
            type="primary" if verdict == 0 else "secondary",
        ):
            if verdict == 0:
                _clear_verdict(trace_id)
            else:
                _submit_and_store(trace_id, 0, turn_index, lang)

        # st.popover, not a hand-rolled menu: its panel portals to the document
        # root and closes on outside-click for free. It holds one item today.
        # No `help=` on this one: the tooltip only restated the icon, and it
        # landed between the row and the menu it opens.
        with st.popover(":material/more_horiz:"):
            if st.button(
                action_label(lang, "view_sources"),
                icon=":material/description:",
                key=f"src_{trace_id}",
            ):
                open_now = st.session_state.sources_open.get(trace_id, False)
                st.session_state.sources_open[trace_id] = not open_now
                st.rerun()

    render_sources(msg, trace_id, lang)
    render_feedback_detail(trace_id, turn_index, lang)


