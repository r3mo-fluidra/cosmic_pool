# Defined up here, not beside `run_turn` below, because the history loop calls it
# and that loop runs before `run_turn`'s own definition is reached.
def render_debug(lines: list[tuple[str, str]]) -> None:
    """
    The old in-conversation telemetry — the planner's step list and the
    per-agent success/error boxes — behind `SHOW_PIPELINE_DEBUG`, collapsed.

    Called from the history loop rather than from inside the turn, for the same
    reason the feedback widget is (FRONTEND.md §11.9): the turn ends in
    `st.rerun()`, so anything rendered during it is discarded a moment later.
    Rendered here it survives, and it stays out of the way of the answer.
    """
    if not (SHOW_PIPELINE_DEBUG and lines):
        return
    with st.expander("Details", expanded=False):
        for kind, text in lines:
            if kind == "error":
                st.error(text)
            elif kind == "info":
                st.info(text)
            else:
                st.markdown(text)


