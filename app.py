# ── Reading position ──────────────────────────────────────────────────────
# Last thing on the page, so the helper's iframe — collapsed to zero height by
# the stylesheet — lands outside the phone and cannot disturb its geometry.
#
# Streamlit leaves a height-constrained container scrolled to the bottom after a
# rerun, so a long answer arrived with its *end* on screen and the reader had to
# scroll back up to find their own question — the most-cited complaint in the
# user-testing sessions. This puts the question near the top instead, with the
# opening lines of the answer under it, and then stops: the conversation reads as
# a flow the user scrolls through, not a jump to the end.
#
# The token changes once per turn, so a mode toggle, a feedback click or any
# other rerun leaves the scroll position exactly where the reader put it.
if st.session_state.turn_counter > 0:
    scroll_to_question(
        token=f"{st.session_state.thread_id}:{st.session_state.turn_counter}"
    )


# `is_definitive_answer` — which decides whether an answer gets the feedback row
# — and `TurnProgress` — which decides what the wait shows — both live in
# `src/ui/turns.py` now. Neither touches Streamlit or the graph, so both are
# unit-tested in test/ui/test_turns.py; from here they are just called.
#
# The three stages the status lines report are the real shape of the graph —
# planner routing, orchestrator retrieval, synthesizer generation — not
# decoration (FRONTEND.md §8.2). That mapping is `TurnProgress`'s contract.


def render_status(slot, rows: list[tuple[str, bool]]) -> None:
    """
    Paint the growing status stack into `slot`.

    `rows` is the whole stack, repainted each time: an `st.empty()` holds one
    element, so advancing a stage means re-rendering the list, not appending to
    it. Into a container rather than straight into the placeholder — writing
    markdown into it directly leaves the previous block behind on some reruns.
    """
    with slot.container():
        status_stack(rows)


def run_turn(
    prompt: str,
    trace_id: str,
    turn_index: int,
    status_slot=None,
) -> tuple[str, bool, list[tuple[str, str]]]:
    """
    Executes the graph and reports progress into `status_slot`.
    Separated from the trace plumbing so the span wrapper stays readable.

    Returns the final response, whether it is a definitive answer, and the
    pipeline-debug lines (see `render_debug`).

    The status stack is `TurnProgress` (src/ui/turns.py); this function's job is
    to translate graph events into calls on it, collect the debug lines, and
    keep the trace plumbing out of both. The language it reports starts from
    `detect_language(prompt)` — the first line has to render before the graph is
    called, so there is nothing else to read yet — and switches to the planner's
    `detected_language` as soon as that arrives. Both are "es"/"en"
    (src/agent/nodes.py:231), so no mapping is needed.
    """
    config = {
        "configurable": {"thread_id": st.session_state.thread_id},
        "callbacks": [CallbackHandler()] if lf else [],
        # No langfuse_trace_id here: in v3 the handler takes trace identity from
        # the active OTel context (the span we open below), not from metadata.
        # These two are plain business metadata, useful when filtering.
        "metadata": {
            "thread_id": st.session_state.thread_id,
            "turn_index": turn_index,
        },
    }

    final_response = ""
    plan_steps: list = []
    suggestions: list[str] = []
    agent_runs: list[tuple[str, str | None]] = []
    debug_lines: list[tuple[str, str]] = []   # (kind, text), replayed below

    def paint(rows: list[tuple[str, bool]]) -> None:
        if status_slot is not None:
            render_status(status_slot, rows)

    # The status stack. Seeded with the guess from the prompt, because the first
    # line has to render before the graph is called and there is nothing else to
    # read yet; it adopts the planner's `detected_language` as soon as that
    # arrives. `paint` runs on each row that actually opens, and only then.
    progress = TurnProgress(detect_language(prompt), on_change=paint)

    # Something on screen before the graph is even called — the wait used to
    # start with nothing at all, which was the whole complaint.
    progress.begin()

    for event in graph.stream(
        {"messages": [HumanMessage(content=prompt)]},
        config=config,
        stream_mode="updates",
    ):
        if "planner" in event:
            plan = event["planner"].get("execution_plan", [])
            plan_steps = list(plan)
            progress.plan(plan_steps, event["planner"].get("detected_language"))

            debug_lines.append(("md", "**Planner Output:**"))
            for step in plan:
                debug_lines.append(
                    ("md", f"- Step {step.step} `[{step.assigned_agent}]`: {step.task}")
                )

        elif "orchestrator" in event:
            # One sub-agent per invocation, looping back to itself — so each
            # pass is a real unit of retrieval and earns the next line.
            progress.step_finished()

            orch_state = event.get("orchestrator")
            if isinstance(orch_state, dict):
                results = orch_state.get("agent_results", {})
                if results:
                    latest_key = sorted(results.keys())[-1]
                    latest_res = results[latest_key]

                    agent_name = getattr(latest_res, "agent", "unknown")
                    error_msg = getattr(latest_res, "error", None)
                    agent_runs.append((agent_name, error_msg))

                    if error_msg:
                        debug_lines.append(
                            ("error", f"**{agent_name.upper()} Agent Error:** {error_msg}")
                        )
                    else:
                        debug_lines.append(
                            ("info", f"**{agent_name.upper()} Agent executed successfully.**")
                        )

        elif "synthesizer" in event:
            # Covers the plan-less case; a no-op when the branch above already
            # opened the generation row.
            progress.generating()
            messages = event["synthesizer"].get("messages", [])
            if messages:
                final_response = messages[-1].content
        elif "suggester" in event:
            # El nodo SIEMPRE escribe la clave, aunque sea con []. Sin esta
            # rama el evento caía al vacío y los chips del grafo no salían
            # nunca de run_turn — los que se veían eran el deck estático.
            suggestions = _chip_texts(event["suggester"].get("suggestions"))
    return (
        final_response,
        is_definitive_answer(plan_steps, agent_runs, final_response),
        debug_lines,
        suggestions,
    )


# User Input — the composer lives inside the phone, above.
# Rendering through `screen_scroll` keeps the live turn inside the phone's
# scroll area, which was laid out before the composer.
if prompt:
    # Monotonic turn index -> the seed is unique even if a previous turn failed.
    st.session_state.turn_counter += 1
    turn_index = st.session_state.turn_counter

    # Deterministic, OTEL-compatible trace id (32 lowercase hex chars).
    current_trace_id = Langfuse.create_trace_id(
        seed=f"{st.session_state.thread_id}:{turn_index}"
    )

    question: ChatMessage = {"role": "user", "content": prompt}
    st.session_state.messages.append(question)
    with screen_scroll.chat_message("user"):
        role_marker("user")
        st.markdown(prompt)

    # The wait, rendered honestly.
    #
    # A plain placeholder rather than `st.status`: that widget draws its own
    # expander chrome and its label ("Agent Thinking Process...") was developer
    # language sitting where an answer belongs.
    #
    # It also sits *outside* `chat_message`, on the bare screen surface, exactly
    # as `.status` does in demo-deep-water.html — the assistant's glass card and
    # its "Your assistant" label only appear once there is something to put in
    # them. Opening the card first promised content that did not exist yet.
    status_slot = screen_scroll.empty()

    final_response = ""
    definitive = False
    debug_lines: list[tuple[str, str]] = []
    suggestions: list[str] = []
    turn_error: Exception | None = None

    if lf is not None:

        with lf.start_as_current_observation(
            as_type="span",
            name=TRACE_NAME,
            trace_context={"trace_id": current_trace_id},
            input={"prompt": prompt},
        ) as span:

            propagate_attributes(
                user_id=st.session_state.thread_id,
                session_id=st.session_state.thread_id,
                tags=["streamlit", "pool-chemistry"],
                metadata={
                    "turn_index": turn_index,
                },
            )

            try:
                final_response, definitive, debug_lines = run_turn(
                    prompt,
                    current_trace_id,
                    turn_index,
                    status_slot=status_slot,
                )

                span.update(
                    output={"response": final_response}
                )

                span.set_trace_io(
                    input={"prompt": prompt},
                    output={"response": final_response},
                )

            except Exception as e:
                turn_error = e

                span.update(
                    level="ERROR",
                    status_message=str(e),
                    output={"error": str(e)},
                )

                span.set_trace_io(
                    input={"prompt": prompt},
                    output={"error": str(e)},
                )

        lf.flush()
    else:
        try:
            final_response, definitive, debug_lines = run_turn(
                prompt, current_trace_id, turn_index,
                status_slot=status_slot,
            )
        except Exception as e:
            turn_error = e

    # Clear the status either way. On the failure path this used to be
    # left mid-flight, so the last thing on screen was a half-finished
    # progress widget above an error.
    status_slot.empty()

    if turn_error is not None:
        # Into the screen, not the page: the guidance belongs inside the phone,
        # the same reasoning as the offline notice above.
        screen_scroll.error(f"El agente falló: {turn_error}")
        st.stop()

    if final_response:
        # Now the card: label and answer together, as one object arriving.
        with screen_scroll.chat_message("assistant"):
            role_marker("assistant")
            assistant_label()
            # Written out rather than pasted in, on the demo's cadence
            # (theme.py::type_out). Presentation only: the text is already
            # complete here, so nothing about the reveal claims the tokens are
            # arriving live. The history loop above renders the same answer
            # instantly on every later rerun — a turn is typed once.
            type_out(st.empty(), final_response)
            render_debug(debug_lines)

        # trace_id + turn_index travel with the message so any past turn
        # stays scorable and its score keeps its conversation coordinates.
        # `can_rate` is decided once, here: a turn cannot become rateable
        # later, and re-deriving it on every rerun would be guesswork from
        # the text alone. Field-by-field documentation is on `ChatMessage`.
        answer: ChatMessage = {
            "role": "assistant",
            "content": final_response,
            "trace_id": current_trace_id,
            "turn_index": turn_index,
            "can_rate": definitive,
            # The chrome under the answer follows the language the reader
            # wrote in, so it is settled once here rather than re-detected
            # from the answer text on every rerun.
            "language": detect_language(prompt),
            # Nothing populates AgentResult.sources yet (FRONTEND.md §15), so
            # this is an empty list today and the panel says so plainly. It is
            # the slot the backend fills when it starts returning them —
            # reading it here changes nothing on that side.
            "sources": [],
            # Only kept when the flag is on: off, this is dead weight in session
            # state for every turn of the conversation.
            "debug": debug_lines if SHOW_PIPELINE_DEBUG else None,
            "suggestions": suggestions,
        }
        st.session_state.messages.append(answer)
        # Rerun so the feedback widget renders from the history loop, where
        # it survives the reruns that its own buttons trigger.
        st.rerun()